def camel(nome: str) -> str:
    inicial, *partes = nome.split('_')
    return inicial + ''.join(parte[:1].upper() + parte[1:] for parte in partes)


def literal(texto: str) -> str:
    return "'" + texto.replace('\\', '\\\\').replace("'", "\\'") + "'"


def caminho_php(caminho: str) -> str:
    partes = []
    posicao = 0
    for encontrado in re.finditer(r'#\{([^}]+)\}', caminho):
        if encontrado.start() > posicao:
            partes.append(literal(caminho[posicao:encontrado.start()]))
        expressao = encontrado.group(1)
        componente = re.fullmatch(r'segmento\(([^)]+)\)', expressao)
        partes.append('$this->segmento($' + camel(componente.group(1)) + ')' if componente else '$' + camel(expressao))
        posicao = encontrado.end()
    if posicao < len(caminho):
        partes.append(literal(caminho[posicao:]))
    return ' . '.join(partes)


def parametros(classe: str, metodo: dict) -> tuple[list[str], list[str]]:
    assinatura = []
    documentacao = []
    for entrada in metodo['parametros'].split(', '):
        if not entrada:
            continue
        nome = entrada.split(' = ')[0]
        opcional = ' = ' in entrada
        variavel = '$' + camel(nome)
        if classe == 'Lotes' and metodo['nome'] == 'enviar':
            assinatura.append('array ' + variavel)
            documentacao.append('@param list<array<string, mixed>|stdClass> ' + variavel)
        elif nome == 'indice':
            assinatura.append('int ' + variavel)
        elif nome == 'ids':
            assinatura.append('array ' + variavel)
            documentacao.append('@param list<string> ' + variavel)
        elif nome == 'topicos':
            assinatura.append('array ' + variavel)
            documentacao.append('@param list<array<string, mixed>|stdClass> ' + variavel)
        elif nome == metodo['consulta']:
            assinatura.append('array ' + variavel + (' = []' if opcional else ''))
            documentacao.append('@param array<string, scalar|null> ' + variavel)
        elif nome in {'pedido', 'dados', 'filtros'}:
            assinatura.append(('array|stdClass|null ' if opcional else 'array|stdClass ') + variavel + (' = null' if opcional else ''))
            documentacao.append('@param array<string, mixed>|stdClass' + ('|null ' if opcional else ' ') + variavel)
        else:
            assinatura.append('string ' + variavel)
    if metodo['formato'] == 'fluxo':
        assinatura.append('callable $consumir')
        documentacao.append('@param callable(string): void $consumir')
    assinatura.append('array $opcoes = []')
    documentacao.append('@param OpcoesRequisicao $opcoes')
    assinatura = ['#[\\SensitiveParameter] ' + parametro for parametro in assinatura]
    return assinatura, documentacao


def corpo_php(metodo: dict) -> str | None:
    corpo = metodo['corpo']
    if corpo is None:
        return None
    if corpo == '{ segmento_id: segmento_id }':
        return "(object) ['segmento_id' => $segmentoId]"
    if corpo == '{ topicos: topicos }':
        return "(object) ['topicos' => $topicos]"
    if corpo == '{ ids: ids }':
        return "(object) ['ids' => $ids]"
    variavel = '$' + camel(corpo)
    if metodo['nome'] == 'enviar' and metodo['caminho'] == '/emails/batch':
        return variavel
    if f'{corpo} = {{}}' in metodo['parametros']:
        return f'({variavel} === null ? new stdClass() : (object) {variavel})'
    return '(object) ' + variavel


def emitir_metodo(classe: str, metodo: dict) -> list[str]:
    assinatura, documentacao = parametros(classe, metodo)
    linhas = ['    /**'] + ['     * ' + linha for linha in documentacao] + ['     */']
    if classe == 'Emails' and metodo['nome'] == 'enviar':
        linhas.insert(1, '     * Aceita a intenção de envio; acompanhe a entrega separadamente.')
    linhas += ['    public function ' + camel(metodo['nome']) + '(']
    linhas += ['        ' + argumento + ',' for argumento in assinatura]
    linhas += ['    ): Resposta {']
    if classe == 'Emails' and metodo['nome'] == 'baixar_anexo':
        linhas += [
            '        if ($indice < 0) {',
            "            throw new ErroConfiguracao('Informe um índice de anexo inteiro e não negativo.');",
            '        }',
            '',
        ]
    if classe == 'Lotes' and metodo['nome'] == 'enviar':
        linhas += [
            '        if (!array_is_list($dados)) {',
            "            throw new ErroConfiguracao('Um lote deve ser uma lista de mensagens.');",
            '        }',
            '',
        ]
    linhas += ['        return $this->executar(', '            ' + literal(metodo['verbo']) + ',', '            ' + caminho_php(metodo['caminho']) + ',']
    corpo = corpo_php(metodo)
    if corpo:
        linhas.append('            corpo: ' + corpo + ',')
    if metodo['consulta']:
        linhas.append('            consulta: $' + camel(metodo['consulta']) + ',')
    if metodo['formato']:
        linhas.append('            formato: ' + literal(metodo['formato']) + ',')
    for nome, valor in metodo['extras'].items():
        linhas.append('            ' + camel(nome) + ': ' + valor + ',')
    linhas.append('            opcoes: $opcoes,')
    if metodo['formato'] == 'fluxo':
        linhas.append('            consumidor: $consumir,')
    linhas += ['        );', '    }']
    return linhas


def emitir_classe(classe: dict) -> str:
    linhas = ['final class ' + classe['nome'] + ' extends RecursoBase', '{']
    if classe['filhos']:
        for filho, tipo in classe['filhos'].items():
            linhas.append('    public readonly ' + tipo + ' $' + camel(filho) + ';')
        linhas += ['', '    public function __construct(TransporteInterface $transporte)', '    {', '        parent::__construct($transporte);']
        linhas += ['        $this->' + camel(filho) + ' = new ' + tipo + '($transporte);' for filho, tipo in classe['filhos'].items()]
        linhas.append('    }')
    for metodo in classe['metodos']:
        if len(linhas) > 2:
            linhas.append('')
        linhas.extend(emitir_metodo(classe['nome'], metodo))
    linhas.append('}')
    corpo = '\n'.join(linhas)
    imports = []
    if 'ErroConfiguracao' in corpo:
        imports.append('use Mailcore\\Excecoes\\ErroConfiguracao;')
    if ': Resposta' in corpo:
        imports.append('use Mailcore\\Resposta;')
    if 'TransporteInterface' in corpo:
        imports.append('use Mailcore\\TransporteInterface;')
    if re.search(r'\bstdClass\b', corpo):
        imports.append('use stdClass;')
    prefixo = [
        '<?php', '', 'declare(strict_types=1);', '', 'namespace Mailcore\\Recursos;', '',
        '// Fonte estática: manutenção em scripts/gerar_recursos.py.',
    ]
    if imports:
        prefixo += imports + ['']
    if classe['metodos']:
        prefixo += [
            '/**',
            ' * @phpstan-type OpcoesRequisicao array{',
            ' *     chaveIdempotencia?: string,',
            ' *     tempoLimite?: int|float,',
            ' *     limiteRespostaBytes?: int,',
            ' *     cabecalhos?: array<string, string>',
            ' * }',
            ' */',
        ]
    return '\n'.join(prefixo) + '\n' + corpo + '\n'


def tokens_php(fonte: str) -> str:
    programa = r'''
$tokens = token_get_all(file_get_contents('php://stdin'), TOKEN_PARSE);
$saida = [];
foreach ($tokens as $token) {
    if (is_array($token)) {
        if (!in_array($token[0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
            $saida[] = [$token[0], $token[1]];
        }
    } else {
        $saida[] = $token;
    }
}
echo json_encode($saida, JSON_THROW_ON_ERROR);
'''
    return subprocess.run(['php', '-r', programa], input=fonte, text=True, capture_output=True, check=True).stdout


def main() -> None:
    argumentos = argparse.ArgumentParser(description=__doc__)
    argumentos.add_argument('--verificar', action='store_true', help='Confere os tokens PHP sem alterar arquivos.')
    opcoes = argumentos.parse_args()
    destino = Path(__file__).resolve().parents[1] / 'src' / 'Recursos'
    divergencias = []
    for classe in ESPECIFICACAO:
        caminho = destino / (classe['nome'] + '.php')
        fonte = emitir_classe(classe)
        if opcoes.verificar:
            if not caminho.exists() or tokens_php(caminho.read_text()) != tokens_php(fonte):
                divergencias.append(caminho.name)
        else:
            caminho.parent.mkdir(parents=True, exist_ok=True)
            caminho.write_text(fonte, encoding='utf-8')
    if divergencias:
        raise SystemExit('Fontes divergentes: ' + ', '.join(divergencias))
    total = sum(len(classe['metodos']) for classe in ESPECIFICACAO)
    print(f'{total} operações conferidas.' if opcoes.verificar else 'Fontes PHP preparadas.')


if __name__ == '__main__':
    main()
